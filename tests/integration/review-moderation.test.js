const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const h = require("./helpers");
const photo = `data:image/jpeg;base64,${fs.readFileSync(path.join(h.ROOT, "images/start.jpeg")).toString("base64")}`;
test.beforeEach(async () => { await h.resetEmulators(); await h.seedProducts(); });

test("đánh giá và ảnh chỉ công khai sau duyệt; ẩn không thay nội dung; chủ đơn vẫn xem được", async () => {
  const buyer = await h.createUser(), stranger = await h.createUser(), admin = await h.createUser("admin");
  const placed = await h.placeOrder({ token: buyer.token });
  const orderId = placed.body.order.id;
  await h.db().doc(`orders/${orderId}`).update({ status: "Đã giao" });
  const body = { action: "review", orderId, rating: 2, comment: "Hoa hơi héo", photos: [photo] };
  assert.equal((await h.callApi("orders", { token: stranger.token, body })).status, 404);
  const created = await h.callApi("orders", { token: buyer.token, body });
  assert.equal(created.status, 201, JSON.stringify(created.body));
  const review = created.body.review;
  assert.equal(review.moderationStatus, "pending");
  assert.equal(review.verifiedPurchase, true);
  assert.equal(review.photoIds.length, 1);
  assert.equal((await h.callApi("orders", { token: buyer.token, body })).body.code, "already-reviewed");
  const own = await h.callApi("orders", { token: buyer.token, body: { action: "review-get", orderId } });
  assert.equal(own.body.review.rating, 2);
  assert.equal((await h.callApi("orders", { token: stranger.token, body: { action: "review-get", orderId } })).status, 404);
  const image = (token) => h.callApi("reviewImages", { method: "GET", token, query: { id: review.photoIds[0] } });
  assert.equal((await image()).status, 404);
  assert.equal((await image(stranger.token)).status, 404);
  assert.equal((await image(buyer.token)).status, 200);
  assert.equal((await image(admin.token)).status, 200);
  await h.db().doc(`reviews/${review.id}`).update({ moderationStatus: "approved" });
  const published = await image();
  assert.equal(published.status, 200);
  assert.equal(published.headers["content-type"], "image/jpeg");
  assert.match(published.headers["cache-control"], /no-store/);
  await h.db().doc(`reviews/${review.id}`).update({ moderationStatus: "hidden", moderationReason: "Có thông tin riêng tư" });
  assert.equal((await image()).status, 404);
  assert.equal((await image(buyer.token)).status, 200);
  const saved = (await h.db().doc(`reviews/${review.id}`).get()).data();
  assert.equal(saved.rating, 2);
  assert.equal(saved.comment, "Hoa hơi héo");
  assert.deepEqual(saved.photoIds, review.photoIds);
});
